/** Locale namespace this half registers its table under. */
export const I18N_NS = 'dshAdmin'

/** Identity dictionary for zh — the keys ARE the zh-CN source strings. Derived
 * from I18N_EN so the two dictionaries cannot drift apart, and materialized
 * lazily so an import in a non-browser context costs nothing. */
var I18N_ZH = null

/** Bound translator once the shell locale service is mounted (null otherwise). */
var boundTranslate = null
/** Locale id the shell reports as active (null until the service is bound). */
var localeActiveId = null
/** setLocale, captured when the service exposes one. */
var localeSetLocale = null
/** Panel-level locale subscribers: the React wrappers re-render through these. */
var localeListeners = new Set()

/**
 * Subscribe to locale changes (the shell's switch and this panel's toggle).
 * @param {() => void} listener - called after every locale change.
 * @returns {() => void} unsubscribe.
 */
export function subscribeLocale(listener) {
  localeListeners.add(listener)
  return function () { localeListeners.delete(listener) }
}

/** The language the panel copy renders in ('en' only when English is active). */
function activeLanguage() {
  if (localeActiveId !== null) return /^en\b/i.test(localeActiveId) ? 'en' : 'zh'
  return I18N_LANG
}

/** One listener throwing must not abort the repaint of the others. */
function notifyLocaleListeners() {
  var snapshot = []
  localeListeners.forEach(function (listener) { snapshot.push(listener) })
  for (var i = 0; i < snapshot.length; i += 1) {
    try { snapshot[i]() } catch (e) { /* a panel must not break the switch */ }
  }
}

/** Read one locale service's active id without trusting its shape. */
function readActiveLocaleId(locale) {
  try {
    var snapshot = typeof locale.getSnapshot === 'function' ? locale.getSnapshot() : null
    return snapshot !== null && typeof snapshot.active === 'string' ? snapshot.active : null
  } catch (e) { return null }
}

/**
 * Adopt the shell locale service when one is mounted: register the table as
 * the dshAdmin namespace, bind it, and mirror its active locale + switch
 * events into this module's listeners.
 * @param {Record<string, any>} ctx - the plugin context.
 * @returns {() => void} disposer (a no-op when the service is absent).
 */
export function installLocaleRuntime(ctx) {
  var locale = typeof ctx.get === 'function' ? ctx.get('locale') : undefined
  if (locale === undefined || locale === null) return function () {}
  if (typeof locale.register !== 'function' || typeof locale.bind !== 'function') return function () {}
  if (I18N_ZH === null) {
    I18N_ZH = {}
    for (var key in I18N_EN) I18N_ZH[key] = key
  }
  // A second materialization of this bundle (HMR, a test harness mounting
  // twice) would hit "already has locale": the table is identical either way,
  // so fall back to binding whatever is registered instead of failing the mount.
  var dispose = null
  try {
    dispose = locale.register(I18N_NS, { zh: I18N_ZH, en: I18N_EN })
  } catch (e) { dispose = null }
  boundTranslate = locale.bind(I18N_NS)
  localeActiveId = readActiveLocaleId(locale)
  localeSetLocale = typeof locale.setLocale === 'function'
    ? function (id) { locale.setLocale(id) }
    : null
  var unsubscribe = typeof locale.subscribe === 'function'
    ? locale.subscribe(function () {
      localeActiveId = readActiveLocaleId(locale)
      notifyLocaleListeners()
    })
    : null
  return function () {
    if (typeof unsubscribe === 'function') unsubscribe()
    boundTranslate = null
    localeActiveId = null
    localeSetLocale = null
    if (typeof dispose === 'function') dispose()
  }
}

/** Translate one UI string. Keys are the zh-CN source strings. */
function dshT(s) {
  if (boundTranslate !== null) {
    var bound = boundTranslate(s)
    return bound === undefined || bound === null || bound === '' ? s : bound
  }
  if (I18N_LANG !== 'en') return s
  var v = I18N_EN[s]
  return v === undefined ? s : v
}

/** Map a possibly-translated label back to its zh-CN source key — for the
 * few lookups that KEY by label (nav icon templates) instead of displaying. */
function i18nSource(s) {
  if (activeLanguage() !== 'en') return s
  for (var k in I18N_EN) {
    if (I18N_EN[k] === s) return k
  }
  return s
}

/** Switch the panel language: through the shell service when bound (live, no
 * reload), else persist and reload so every panel re-reads. */
function setAdminLang(lang) {
  var next = lang === 'en' ? 'en' : 'zh'
  try { window.localStorage.setItem('dsh-admin-lang', next) } catch (e) { /* ignore */ }
  if (localeSetLocale !== null) { localeSetLocale(next); return }
  window.location.reload()
}

/** The language the panel copy currently renders in ('en' or 'zh'). */
export function currentLanguage() {
  return activeLanguage()
}

export { I18N_EN, I18N_LANG, I18N_ZH, dshT, i18nSource, setAdminLang }
