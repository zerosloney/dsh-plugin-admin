/**
 * Panel copy: the two-language layer for the browser half.
 *
 * Phase C — this half now rides the shell's own locale service when one is
 * mounted (ctx.locale, provided by @deepseek-ai/dsh-client-locale in every
 * web deployment) instead of being a private island:
 *
 *   - installLocaleRuntime(ctx) registers the table as the dshAdmin
 *     namespace ({ zh, en }) and binds it, so the ACTIVE locale is the
 *     shell's and a shell language switch repaints these panels live — the
 *     old reload-based toggle is gone;
 *   - dshT() reads the bound translator at call time and falls back to the
 *     previous two-language behavior when no service is mounted (tests,
 *     headless mounts), so a missing service degrades instead of breaking;
 *   - the zh dictionary is DERIVED from the en table's keys (identity
 *     mapping). It has to exist: the locale runtime walks a fallback chain,
 *     and with only `en` registered a zh reader would be served English.
 *
 * The zh-CN source strings ARE the keys: dshT() returns them verbatim in
 * Chinese and the I18N_EN mapping in English, falling back to the source for
 * any untranslated key — so the UI can never break while coverage grows.
 * Without the service, the language comes from localStorage
 * 'dsh-admin-lang', else navigator.language ("en…" → English, else
 * Chinese), and setAdminLang() persists + reloads.
 */
var I18N_LANG = (function () {
  try {
    var saved = window.localStorage && window.localStorage.getItem('dsh-admin-lang')
    if (saved === 'en' || saved === 'zh') return saved
  } catch (e) { /* private-mode storage: fall through to navigator */ }
  return /^en\b/i.test(String((typeof navigator !== 'undefined' && navigator.language) || '')) ? 'en' : 'zh'
})()

